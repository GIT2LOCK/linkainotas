-- ============================================ claims internos no token
CREATE OR REPLACE FUNCTION public.custom_access_token_hook(event jsonb)
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path TO 'public'
AS $$
DECLARE
  v_claims jsonb;
  v_usuario record;
  v_perfil text := 'sem_acesso';
BEGIN
  v_claims := COALESCE(event -> 'claims', '{}'::jsonb);

  SELECT u.id, u.empresa_id, u.ariia_user_id, u.ativo, u.is_platform_superadmin
    INTO v_usuario
  FROM public.usuarios u
  WHERE u.auth_user_id = (event ->> 'user_id')::uuid;

  IF FOUND THEN
    IF COALESCE(v_usuario.is_platform_superadmin, false) THEN
      v_perfil := 'superadmin_2lock';
    ELSE
      SELECT COALESCE((
        SELECT uo.perfil_codigo FROM public.linkai_usuario_obras uo
         WHERE uo.usuario_id = v_usuario.id AND uo.ativo
         ORDER BY uo.principal DESC, uo.created_at LIMIT 1), 'sem_acesso')
        INTO v_perfil;
    END IF;

    v_claims := jsonb_set(v_claims, '{empresa_id}', COALESCE(to_jsonb(v_usuario.empresa_id), 'null'::jsonb), true);
    v_claims := jsonb_set(v_claims, '{ariia_user_id}', COALESCE(to_jsonb(v_usuario.ariia_user_id), 'null'::jsonb), true);
    v_claims := jsonb_set(v_claims, '{usuario_id}', to_jsonb(v_usuario.id), true);
    v_claims := jsonb_set(v_claims, '{ativo}', to_jsonb(COALESCE(v_usuario.ativo, false)), true);
    v_claims := jsonb_set(v_claims, '{is_platform_superadmin}',
      to_jsonb(COALESCE(v_usuario.is_platform_superadmin, false)), true);
  ELSE
    v_claims := jsonb_set(v_claims, '{empresa_id}', 'null'::jsonb, true);
    v_claims := jsonb_set(v_claims, '{ariia_user_id}', 'null'::jsonb, true);
    v_claims := jsonb_set(v_claims, '{usuario_id}', 'null'::jsonb, true);
    v_claims := jsonb_set(v_claims, '{ativo}', 'false'::jsonb, true);
    v_claims := jsonb_set(v_claims, '{is_platform_superadmin}', 'false'::jsonb, true);
  END IF;

  v_claims := jsonb_set(v_claims, '{perfil_interno}', to_jsonb(v_perfil), true);
  v_claims := jsonb_set(v_claims, '{permissao}', to_jsonb(v_perfil), true);

  RETURN jsonb_set(event, '{claims}', v_claims, true);
END;
$$;

-- ============================================= fila do Lumina com obra
CREATE OR REPLACE FUNCTION public.enqueue_lumina_request(
  p_action text DEFAULT 'launch_notes',
  p_payload jsonb DEFAULT '{}'::jsonb,
  p_items jsonb DEFAULT '[]'::jsonb
)
RETURNS public.lumina_queue_requests
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $$
DECLARE
  v_user uuid := auth.uid();
  v_usuario_id integer := public.linkai_current_usuario_id();
  v_empresa integer := public.linkai_current_empresa_id();
  v_obra uuid := public.linkai_obra_principal(v_usuario_id);
  v_items jsonb := COALESCE(p_items, '[]'::jsonb);
  v_count integer;
  v_request public.lumina_queue_requests;
BEGIN
  IF v_user IS NULL OR v_usuario_id IS NULL THEN
    RAISE EXCEPTION 'Usuário não autenticado ou inativo.' USING ERRCODE = '42501';
  END IF;

  IF NOT public.linkai_has_permissao('notes.launch') THEN
    RAISE EXCEPTION 'Permissão insuficiente para lançar notas.' USING ERRCODE = '42501';
  END IF;

  IF COALESCE(p_action, 'launch_notes') <> 'launch_notes' THEN
    RAISE EXCEPTION 'Ação inválida para a fila do Lumina: %', p_action;
  END IF;

  IF jsonb_typeof(v_items) <> 'array' THEN
    RAISE EXCEPTION 'A lista de itens deve ser um array JSON.';
  END IF;

  IF jsonb_array_length(v_items) = 0 THEN
    v_items := jsonb_build_array(COALESCE(p_payload, '{}'::jsonb));
  END IF;

  v_count := jsonb_array_length(v_items);
  IF v_count > 1000 THEN
    RAISE EXCEPTION 'A solicitação excede o limite de 1000 itens.';
  END IF;

  INSERT INTO public.lumina_queue_requests (
    requested_by, empresa_id, obra_id, action, status, total_items, message
  ) VALUES (
    v_user, v_empresa, v_obra, 'launch_notes', 'queued', v_count,
    'Solicitação registrada na fila. Aguardando uma máquina disponível.'
  ) RETURNING * INTO v_request;

  INSERT INTO public.lumina_jobs (
    requested_by, empresa_id, obra_id, action, status, payload, message, queue_request_id, item_number
  )
  SELECT
    v_user, v_empresa, v_obra, 'launch_notes', 'queued',
    CASE WHEN jsonb_typeof(item.value) = 'object' THEN item.value ELSE jsonb_build_object('value', item.value) END,
    'Solicitação registrada na fila. Aguardando uma máquina disponível.',
    v_request.id, item.ordinality::int
  FROM jsonb_array_elements(v_items) WITH ORDINALITY AS item(value, ordinality);

  PERFORM public.linkai_log_activity(
    'notes.launch.enqueued', 'started',
    jsonb_build_object('total_items', v_count, 'queue_number', v_request.queue_number),
    'Solicitação de lançamento de notas registrada na fila.', v_obra);

  RETURN v_request;
END;
$$;

-- propaga obra_id do job para o log de arquivamento
CREATE OR REPLACE FUNCTION public.lumina_archive_job(p_job_id uuid, p_status text, p_message text)
RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $$
DECLARE
  v_job public.lumina_jobs;
  v_number bigint;
  v_request uuid;
BEGIN
  SELECT * INTO v_job FROM public.lumina_jobs WHERE id = p_job_id FOR UPDATE;
  IF NOT FOUND THEN RETURN false; END IF;

  SELECT queue_number INTO v_number
  FROM public.lumina_queue_requests WHERE id = v_job.queue_request_id;

  INSERT INTO public.lumina_queue_logs (
    queue_request_id, queue_item_id, queue_number, item_number, requested_by, empresa_id, obra_id,
    action, status, payload, worker_id, attempts, queued_at, started_at, finished_at, message
  ) VALUES (
    v_job.queue_request_id, v_job.id, COALESCE(v_number, 0), COALESCE(v_job.item_number, 1),
    v_job.requested_by, v_job.empresa_id, v_job.obra_id, v_job.action, p_status,
    COALESCE(v_job.payload, '{}'::jsonb),
    v_job.worker_id, v_job.attempts, v_job.created_at, v_job.started_at, now(), p_message
  );

  v_request := v_job.queue_request_id;
  DELETE FROM public.lumina_jobs WHERE id = v_job.id;
  PERFORM public.lumina_refresh_request(v_request);
  RETURN true;
END;
$$;

