-- ------------------------------------------------------- perfis internos
CREATE TABLE IF NOT EXISTS public.linkai_perfis_internos (
  codigo text PRIMARY KEY,
  nome text NOT NULL,
  descricao text,
  escopo text NOT NULL CHECK (escopo IN ('plataforma','empresa','obra')),
  nivel integer NOT NULL DEFAULT 0,
  ativo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.linkai_permissoes (
  codigo text PRIMARY KEY,
  nome text NOT NULL,
  descricao text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.linkai_perfil_permissoes (
  perfil_codigo text NOT NULL REFERENCES public.linkai_perfis_internos(codigo) ON DELETE CASCADE,
  permissao_codigo text NOT NULL REFERENCES public.linkai_permissoes(codigo) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (perfil_codigo, permissao_codigo)
);

-- ----------------------------------------------------------------- obras
CREATE TABLE IF NOT EXISTS public.linkai_obras (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  empresa_id integer NOT NULL REFERENCES public.empresas(id) ON DELETE CASCADE,
  codigo text NOT NULL,
  nome text NOT NULL,
  tipo text NOT NULL DEFAULT 'obra' CHECK (tipo IN ('escritorio','obra')),
  ativo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS linkai_obras_codigo_empresa_uniq
  ON public.linkai_obras (empresa_id, upper(codigo));
CREATE UNIQUE INDEX IF NOT EXISTS linkai_obras_um_escritorio_ativo
  ON public.linkai_obras (empresa_id) WHERE tipo = 'escritorio' AND ativo;
CREATE INDEX IF NOT EXISTS linkai_obras_empresa_idx ON public.linkai_obras (empresa_id);

-- ------------------------------------------------------ usuario x obras
CREATE TABLE IF NOT EXISTS public.linkai_usuario_obras (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  usuario_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  obra_id uuid NOT NULL REFERENCES public.linkai_obras(id) ON DELETE CASCADE,
  perfil_codigo text NOT NULL REFERENCES public.linkai_perfis_internos(codigo),
  principal boolean NOT NULL DEFAULT false,
  ativo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS linkai_usuario_obras_ativa_uniq
  ON public.linkai_usuario_obras (usuario_id, obra_id) WHERE ativo;
CREATE UNIQUE INDEX IF NOT EXISTS linkai_usuario_obras_uma_principal
  ON public.linkai_usuario_obras (usuario_id) WHERE principal AND ativo;
CREATE INDEX IF NOT EXISTS linkai_usuario_obras_obra_idx ON public.linkai_usuario_obras (obra_id);

-- -------------------------------------------------------------- convites
CREATE TABLE IF NOT EXISTS public.linkai_user_convites (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  nome text NOT NULL,
  email text NOT NULL,
  empresa_id integer NOT NULL REFERENCES public.empresas(id) ON DELETE CASCADE,
  obra_id uuid REFERENCES public.linkai_obras(id) ON DELETE SET NULL,
  perfil_codigo text NOT NULL REFERENCES public.linkai_perfis_internos(codigo),
  two_factor_policy text NOT NULL DEFAULT 'optional'
    CHECK (two_factor_policy IN ('required','optional','disabled')),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','linked','canceled')),
  criado_por uuid,
  criado_em timestamptz NOT NULL DEFAULT now(),
  vinculado_em timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS linkai_user_convites_pending_email
  ON public.linkai_user_convites (lower(email)) WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS linkai_user_convites_empresa_idx
  ON public.linkai_user_convites (empresa_id);

-- --------------------------------------------------------- activity logs
CREATE TABLE IF NOT EXISTS public.linkai_activity_logs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  actor_user_id uuid,
  actor_usuario_id integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
  empresa_id integer REFERENCES public.empresas(id) ON DELETE SET NULL,
  obra_id uuid REFERENCES public.linkai_obras(id) ON DELETE SET NULL,
  action text NOT NULL,
  status text NOT NULL DEFAULT 'started' CHECK (status IN ('started','succeeded','failed','canceled','info')),
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  message text,
  created_at timestamptz NOT NULL DEFAULT now(),
  started_at timestamptz,
  finished_at timestamptz
);

CREATE INDEX IF NOT EXISTS linkai_activity_logs_actor_idx ON public.linkai_activity_logs (actor_usuario_id, created_at DESC);
CREATE INDEX IF NOT EXISTS linkai_activity_logs_obra_idx ON public.linkai_activity_logs (obra_id, created_at DESC);
CREATE INDEX IF NOT EXISTS linkai_activity_logs_empresa_idx ON public.linkai_activity_logs (empresa_id, created_at DESC);

