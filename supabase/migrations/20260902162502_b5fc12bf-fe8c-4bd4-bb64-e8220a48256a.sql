-- ============================================== ESCRITORIO automático
CREATE OR REPLACE FUNCTION public.linkai_ensure_escritorio(p_empresa_id integer)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE v_id uuid;
BEGIN
  SELECT id INTO v_id FROM public.linkai_obras
   WHERE empresa_id = p_empresa_id AND tipo = 'escritorio' AND ativo LIMIT 1;
  IF v_id IS NOT NULL THEN RETURN v_id; END IF;

  INSERT INTO public.linkai_obras (empresa_id, codigo, nome, tipo, ativo)
  VALUES (p_empresa_id, 'ESCRITORIO', 'ESCRITORIO', 'escritorio', true)
  ON CONFLICT (empresa_id, upper(codigo))
  DO UPDATE SET ativo = true, tipo = 'escritorio'
  RETURNING id INTO v_id;

  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.linkai_empresa_escritorio_trigger()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
BEGIN
  PERFORM public.linkai_ensure_escritorio(NEW.id);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS linkai_empresas_escritorio ON public.empresas;
CREATE TRIGGER linkai_empresas_escritorio AFTER INSERT ON public.empresas
  FOR EACH ROW EXECUTE FUNCTION public.linkai_empresa_escritorio_trigger();

