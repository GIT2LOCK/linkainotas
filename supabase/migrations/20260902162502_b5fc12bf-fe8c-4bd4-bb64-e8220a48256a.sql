CREATE OR REPLACE FUNCTION public.linkai_current_usuario()
RETURNS public.usuarios
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public'
AS $$ SELECT u.* FROM public.usuarios u WHERE u.auth_user_id = auth.uid() LIMIT 1 $$;

CREATE OR REPLACE FUNCTION public.linkai_current_usuario_id()
RETURNS integer
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public'
AS $$ SELECT u.id FROM public.usuarios u WHERE u.auth_user_id = auth.uid() AND u.ativo LIMIT 1 $$;

CREATE OR REPLACE FUNCTION public.linkai_current_empresa_id()
RETURNS integer
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public'
AS $$ SELECT u.empresa_id FROM public.usuarios u WHERE u.auth_user_id = auth.uid() AND u.ativo LIMIT 1 $$;

CREATE OR REPLACE FUNCTION public.linkai_is_platform_superadmin()
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public'
AS $$
  SELECT COALESCE((SELECT u.is_platform_superadmin AND u.ativo FROM public.usuarios u
                    WHERE u.auth_user_id = auth.uid() LIMIT 1), false)
$$;

CREATE OR REPLACE FUNCTION public.linkai_perfil_principal(p_usuario_id integer DEFAULT NULL)
RETURNS text
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public'
AS $$
  WITH alvo AS (
    SELECT COALESCE(p_usuario_id,
      (SELECT u.id FROM public.usuarios u WHERE u.auth_user_id = auth.uid() LIMIT 1)) AS id
  )
  SELECT CASE
    WHEN (SELECT COALESCE(u.is_platform_superadmin, false) FROM public.usuarios u, alvo
           WHERE u.id = alvo.id) THEN 'superadmin_2lock'
    ELSE COALESCE((
      SELECT uo.perfil_codigo FROM public.linkai_usuario_obras uo, alvo
       WHERE uo.usuario_id = alvo.id AND uo.ativo
       ORDER BY uo.principal DESC, uo.created_at
       LIMIT 1), 'sem_acesso')
  END
$$;

CREATE OR REPLACE FUNCTION public.linkai_is_supervisor()
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public'
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.linkai_usuario_obras uo
      JOIN public.usuarios u ON u.id = uo.usuario_id
     WHERE u.auth_user_id = auth.uid() AND u.ativo AND uo.ativo
       AND uo.perfil_codigo = 'supervisor_empresa'
  )
$$;

CREATE OR REPLACE FUNCTION public.linkai_has_permissao(_permissao text)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public'
AS $$
  SELECT public.linkai_is_platform_superadmin() OR EXISTS (
    SELECT 1 FROM public.linkai_usuario_obras uo
      JOIN public.usuarios u ON u.id = uo.usuario_id
      JOIN public.linkai_perfil_permissoes pp ON pp.perfil_codigo = uo.perfil_codigo
     WHERE u.auth_user_id = auth.uid() AND u.ativo AND uo.ativo
       AND pp.permissao_codigo = _permissao
  )
$$;

-- obras visíveis ao usuário corrente
CREATE OR REPLACE FUNCTION public.linkai_obras_visiveis()
RETURNS SETOF uuid
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public'
AS $$
  SELECT o.id FROM public.linkai_obras o
   WHERE public.linkai_is_platform_superadmin()
      OR (public.linkai_is_supervisor() AND o.empresa_id = public.linkai_current_empresa_id())
      OR EXISTS (
        SELECT 1 FROM public.linkai_usuario_obras uo
          JOIN public.usuarios u ON u.id = uo.usuario_id
         WHERE uo.obra_id = o.id AND uo.ativo AND u.ativo AND u.auth_user_id = auth.uid())
$$;

CREATE OR REPLACE FUNCTION public.linkai_can_access_obra(p_obra_id uuid)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public'
AS $$
  SELECT p_obra_id IS NOT NULL
     AND p_obra_id IN (SELECT public.linkai_obras_visiveis())
$$;

CREATE OR REPLACE FUNCTION public.linkai_can_manage_empresa(p_empresa_id integer)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public'
AS $$
  SELECT public.linkai_is_platform_superadmin()
      OR (public.linkai_has_permissao('access.manage')
          AND p_empresa_id IS NOT NULL
          AND p_empresa_id = public.linkai_current_empresa_id())
$$;

CREATE OR REPLACE FUNCTION public.linkai_obra_principal(p_usuario_id integer DEFAULT NULL)
RETURNS uuid
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public'
AS $$
  WITH alvo AS (
    SELECT COALESCE(p_usuario_id,
      (SELECT u.id FROM public.usuarios u WHERE u.auth_user_id = auth.uid() LIMIT 1)) AS id
  )
  SELECT uo.obra_id FROM public.linkai_usuario_obras uo, alvo
   WHERE uo.usuario_id = alvo.id AND uo.ativo
   ORDER BY uo.principal DESC, uo.created_at LIMIT 1
$$;

-- ======================================== atribuição atômica de usuário
CREATE OR REPLACE FUNCTION public.linkai_assign_user_to_obra(
  p_usuario_id integer,
  p_obra_id uuid,
  p_perfil_codigo text,
  p_principal boolean DEFAULT false
)
RETURNS public.linkai_usuario_obras
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE
  v_usuario public.usuarios;
  v_obra public.linkai_obras;
  v_perfil public.linkai_perfis_internos;
  v_row public.linkai_usuario_obras;
  v_is_service boolean := (current_setting('request.jwt.claims', true) IS NULL);
BEGIN
  SELECT * INTO v_usuario FROM public.usuarios WHERE id = p_usuario_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Usuário não encontrado.' USING ERRCODE = '22023'; END IF;
  IF NOT COALESCE(v_usuario.ativo, false) THEN
    RAISE EXCEPTION 'Usuário inativo.' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO v_obra FROM public.linkai_obras WHERE id = p_obra_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Obra não encontrada.' USING ERRCODE = '22023'; END IF;
  IF NOT v_obra.ativo THEN RAISE EXCEPTION 'Obra inativa.' USING ERRCODE = '22023'; END IF;

  SELECT * INTO v_perfil FROM public.linkai_perfis_internos WHERE codigo = p_perfil_codigo AND ativo;
  IF NOT FOUND THEN RAISE EXCEPTION 'Perfil interno inválido: %', p_perfil_codigo USING ERRCODE = '22023'; END IF;

  IF p_perfil_codigo = 'superadmin_2lock' THEN
    RAISE EXCEPTION 'O perfil superadmin_2lock é de plataforma e não pode ser atribuído a uma obra.'
      USING ERRCODE = '22023';
  END IF;

  IF p_perfil_codigo = 'supervisor_empresa' AND v_obra.tipo <> 'escritorio' THEN
    RAISE EXCEPTION 'supervisor_empresa só pode ser atribuído ao ESCRITORIO da empresa.'
      USING ERRCODE = '22023';
  END IF;

  IF v_usuario.empresa_id IS NULL OR v_usuario.empresa_id <> v_obra.empresa_id THEN
    RAISE EXCEPTION 'Usuário e obra pertencem a empresas diferentes.' USING ERRCODE = '22023';
  END IF;

  -- Autorização: service_role (sem JWT) passa direto; caso contrário exige poder
  -- administrar a empresa da obra.
  IF NOT v_is_service AND auth.uid() IS NOT NULL THEN
    IF NOT public.linkai_can_manage_empresa(v_obra.empresa_id) THEN
      RAISE EXCEPTION 'Permissão insuficiente para administrar acessos desta empresa.'
        USING ERRCODE = '42501';
    END IF;
  END IF;

  -- Serializa por usuário e desativa a principal anterior na mesma transação.
  PERFORM pg_advisory_xact_lock(hashtextextended('linkai_assign'::text, p_usuario_id));

  IF p_principal THEN
    UPDATE public.linkai_usuario_obras
       SET principal = false
     WHERE usuario_id = p_usuario_id AND principal AND ativo AND obra_id <> p_obra_id;
  END IF;

  INSERT INTO public.linkai_usuario_obras (usuario_id, obra_id, perfil_codigo, principal, ativo)
  VALUES (p_usuario_id, p_obra_id, p_perfil_codigo, COALESCE(p_principal, false), true)
  ON CONFLICT (usuario_id, obra_id) WHERE ativo
  DO UPDATE SET perfil_codigo = EXCLUDED.perfil_codigo,
                principal = EXCLUDED.principal,
                ativo = true,
                updated_at = now()
  RETURNING * INTO v_row;

  RETURN v_row;
END;
$$;

REVOKE ALL ON FUNCTION public.linkai_assign_user_to_obra(integer, uuid, text, boolean) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.linkai_assign_user_to_obra(integer, uuid, text, boolean)
  TO authenticated, service_role;

-- criação de obra comum
CREATE OR REPLACE FUNCTION public.linkai_create_obra(
  p_empresa_id integer, p_codigo text, p_nome text, p_tipo text DEFAULT 'obra'
)
RETURNS public.linkai_obras
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $$
DECLARE v_row public.linkai_obras;
BEGIN
  IF auth.uid() IS NOT NULL AND NOT (
      public.linkai_is_platform_superadmin()
      OR (public.linkai_has_permissao('works.manage')
          AND p_empresa_id = public.linkai_current_empresa_id())) THEN
    RAISE EXCEPTION 'Permissão insuficiente para criar obras nesta empresa.' USING ERRCODE = '42501';
  END IF;

  IF COALESCE(p_tipo,'obra') NOT IN ('obra','escritorio') THEN
    RAISE EXCEPTION 'Tipo de obra inválido: %', p_tipo USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.linkai_obras (empresa_id, codigo, nome, tipo)
  VALUES (p_empresa_id, upper(trim(p_codigo)), p_nome, COALESCE(p_tipo,'obra'))
  RETURNING * INTO v_row;
  RETURN v_row;
END;
$$;

REVOKE ALL ON FUNCTION public.linkai_create_obra(integer, text, text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.linkai_create_obra(integer, text, text, text) TO authenticated, service_role;

-- vínculo de convite no primeiro acesso
CREATE OR REPLACE FUNCTION public.linkai_link_convite(p_email text)
RETURNS public.linkai_user_convites
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $$
DECLARE
  v_convite public.linkai_user_convites;
  v_usuario public.usuarios;
  v_obra uuid;
BEGIN
  SELECT * INTO v_convite FROM public.linkai_user_convites
   WHERE lower(email) = lower(p_email) AND status = 'pending' FOR UPDATE;
  IF NOT FOUND THEN RETURN NULL; END IF;

  SELECT * INTO v_usuario FROM public.usuarios WHERE lower(email) = lower(p_email) FOR UPDATE;
  IF NOT FOUND THEN RETURN NULL; END IF;

  UPDATE public.usuarios
     SET empresa_id = v_convite.empresa_id,
         two_factor_policy = v_convite.two_factor_policy,
         atualizado_em = now()
   WHERE id = v_usuario.id;

  v_obra := COALESCE(v_convite.obra_id, public.linkai_ensure_escritorio(v_convite.empresa_id));

  IF v_convite.perfil_codigo <> 'superadmin_2lock' THEN
    PERFORM public.linkai_assign_user_to_obra(v_usuario.id, v_obra, v_convite.perfil_codigo, true);
  END IF;

  UPDATE public.linkai_user_convites
     SET status = 'linked', vinculado_em = now()
   WHERE id = v_convite.id
  RETURNING * INTO v_convite;

  RETURN v_convite;
END;
$$;

REVOKE ALL ON FUNCTION public.linkai_link_convite(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.linkai_link_convite(text) TO service_role;

-- registro de atividade (somente metadados)
CREATE OR REPLACE FUNCTION public.linkai_log_activity(
  p_action text,
  p_status text DEFAULT 'info',
  p_payload jsonb DEFAULT '{}'::jsonb,
  p_message text DEFAULT NULL,
  p_obra_id uuid DEFAULT NULL,
  p_started_at timestamptz DEFAULT NULL,
  p_finished_at timestamptz DEFAULT NULL
)
RETURNS uuid
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $$
DECLARE
  v_usuario public.usuarios;
  v_obra uuid;
  v_id uuid;
BEGIN
  SELECT * INTO v_usuario FROM public.usuarios WHERE auth_user_id = auth.uid() LIMIT 1;
  v_obra := COALESCE(p_obra_id, public.linkai_obra_principal(v_usuario.id));

  INSERT INTO public.linkai_activity_logs (
    actor_user_id, actor_usuario_id, empresa_id, obra_id, action, status,
